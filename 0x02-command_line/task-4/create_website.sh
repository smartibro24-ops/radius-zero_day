#!/bin/bash

# Default location, or the first argument if given
DEST="${1:-$HOME/radius-projects/website-project}"

# Protect existing directories
if [ -e "$DEST" ]; then
  echo "Error: '$DEST' already exists. Nothing was changed."
  exit 1
fi

# Create the structure
mkdir -p "$DEST/css" "$DEST/js" "$DEST/images" || exit 1

cat > "$DEST/index.html" <<'EOF'
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>My Website</title>
  <link rel="stylesheet" href="css/style.css">
</head>
<body>
  <h1>Welcome to My Website</h1>
  <p>This page was generated by create_website.sh</p>
  <script src="js/script.js"></script>
</body>
</html>
EOF

cat > "$DEST/css/style.css" <<'EOF'
body {
  font-family: Arial, sans-serif;
  margin: 2rem;
  background-color: #f4f4f4;
  color: #222;
}

h1 {
  color: #0a66c2;
}
EOF

cat > "$DEST/js/script.js" <<'EOF'
console.log("Website loaded successfully!");
EOF

cat > "$DEST/README.md" <<'EOF'
# Website Project
A basic website with HTML, CSS and JavaScript, generated by a Bash script.
EOF

cat > "$DEST/css/README.md" <<'EOF'
# css/
This directory holds the stylesheets that control how the website looks.
EOF

cat > "$DEST/js/README.md" <<'EOF'
# js/
This directory holds the JavaScript files that add behaviour to the website.
EOF

cat > "$DEST/images/README.md" <<'EOF'
# images/
This directory holds image files such as .png, .jpg, .svg, .gif and .webp.
EOF

echo "Website project created at: $(cd "$DEST" && pwd)"
